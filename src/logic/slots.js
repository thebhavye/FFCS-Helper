export const splitSlotCode = (code) =>
  code.split("+").map((s) => s.trim()).filter(Boolean);

export function isClash(slotA, slotB) {
  const timesA = slotTimes[slotA] || [];
  const timesB = slotTimes[slotB] || [];
  return timesA.some((tA) =>
    timesB.some((tB) => tA[0] === tB[0] && tA[1] < tB[2] && tA[2] > tB[1])
  );
}

export function hasAnyClash(slots, occupiedSlots) {
  return slots.some((slot) => occupiedSlots.some((existing) => isClash(slot, existing)));
}

export function conflictsWithSelection(code, selectedSlots) {
  const slots = splitSlotCode(code);
  return slots.some((slot) =>
    selectedSlots.some((selected) => slot !== selected && isClash(slot, selected))
  );
}
